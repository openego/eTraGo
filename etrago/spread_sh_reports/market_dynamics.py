"""Market-dynamics page: price levels, distributions, daily patterns, market
values and time series per bidding zone - inspired by Fraunhofer IEE (2026)
"Strommarktuntersuchung einer gemeinsamen Strompreiszone aus
Schleswig-Holstein, Hamburg und Dänemark-West" (NTSZ study for EKSH).

Indicators are compared against the single zone (status quo) for the same
plants / the same area, as in the IEE study.
"""

import numpy as np
import pandas as pd

from . import charts as C
from . import geo
from . import html as H
from .config import SCENARIO_COLOR, SCENARIO_LABELS
from .report import base_map, zone_anchor

SURPLUS = 3.0     # €/MWh: price set by wind/solar (eTraGo has no negative bids)
LOW, HIGH = 20.0, 100.0
WEEKDAYS = ["Mon", "Tue", "Wed", "Thu", "Fri", "Sat", "Sun"]
WIND = ["wind_onshore", "wind_offshore"]
PV = ["solar", "solar_rooftop"]


def _wmean(v, w):
    v = np.asarray(v, float)
    w = np.asarray(w, float)
    return float((v * w).sum() / w.sum()) if w.sum() else np.nan


class MarketDynamicsReport:
    def __init__(self, metrics, nav, links, data_dir, plotly_js=None):
        self.M = metrics
        self.nav = nav
        self.links = links
        self.data_dir = data_dir
        self.plotly_js = plotly_js
        self.figs = {}
        self.sections = []
        self.toc = []
        self.sq = "status_quo" if "status_quo" in metrics else next(iter(metrics))
        self.splits = [k for k in metrics if k != self.sq]
        self._plant_data()

    fig = lambda self, fid, spec: (self.figs.__setitem__(fid, spec), fid)[1]

    def add(self, sid, title, lead, body):
        self.toc.append((sid, title))
        self.sections.append(H.section(sid, title, lead, body))

    # ------------------------------------------------------------------
    def _plant_data(self):
        """Per-plant market dispatch, revenue and curtailment for wind, PV and
        electrolysers in every configuration (same plant names in all runs)."""
        self.plants = {}
        for k, m in self.M.items():
            mk = m.mkt
            w = mk.weights
            mg = mk.static("generators")
            gg = m.grid.static("generators")
            sel = mg.index[mg.carrier.isin(WIND + PV)].intersection(gg.index)
            p = mk.series("generators", "p").reindex(columns=sel, fill_value=0)
            price = pd.DataFrame({g: m.prices[m.mkt_zone[mg.at[g, "bus"]]].values for g in sel},
                                 index=p.index)
            avail = mk.dense("generators", "p_max_pu", columns=sel).mul(mg.loc[sel, "p_nom"], axis=1)
            df = pd.DataFrame({
                "carrier": mg.loc[sel, "carrier"],
                "bus": gg.loc[sel, "bus"],
                "energy": p.mul(w, axis=0).sum(),
                "revenue": (p * price).mul(w, axis=0).sum(),
                "avail": avail.mul(w, axis=0).sum(),
            })
            df["curt"] = (df.avail - df.energy).clip(lower=0)
            self.plants[k] = df
            # Electrolysers (market model) located by their AC bus
            ml = mk.static("links")
            ely = ml[ml.carrier == "power_to_H2"]
            p0 = mk.series("links", "p0").reindex(columns=ely.index, fill_value=0).clip(lower=0)
            m._ely_mkt = pd.DataFrame({"zone": ely.bus0.map(m.mkt_zone),
                                       "mwh": p0.mul(w, axis=0).sum(),
                                       "p_nom": ely.p_nom_opt.fillna(ely.p_nom)})
            m._ely_ts = p0.T.groupby(ely.bus0.map(m.mkt_zone)).sum().T

    def _zone_of_plants(self, k):
        """Zone of every plant according to configuration k (same plant set)."""
        m = self.M[k]
        return self.plants[k].bus.map(m.bus_zone)

    # ------------------------------------------------------------------
    def build(self):
        self.price_hours()
        self.distribution()
        self.daily_pattern()
        self.duration()
        self.zone_effects()
        self.explorer()
        return H.page(
            title="SPREAD.SH market dynamics",
            heading="Market dynamics per bidding zone",
            intro=("Price levels, distributions, daily patterns and market values of the bidding zones, "
                   "compared against the single DE/LU zone – following the indicators of the Fraunhofer IEE "
                   "short study on a joint price zone of Schleswig-Holstein, Hamburg and western Denmark "
                   "(NTSZ, 2026)."),
            chips=["market model prices", "5-h snapshots × 5 h", "reference: single zone",
                   "SH = zone containing Schleswig-Holstein"],
            nav=self.nav, toc=self.toc, sections_html="".join(self.sections), figs=self.figs,
            plotly_js=self.plotly_js, footer="Generated by spread_sh_reports.",
        )

    # ------------------------------------------------------------------
    def price_hours(self):
        rows = []
        for k, m in self.M.items():
            w = m.mkt.weights
            for z in m.de_zones:
                p = m.prices[z]
                curt = self._zone_curt_ts(k, z)
                rows.append({
                    "Configuration": SCENARIO_LABELS.get(k, k), "Zone": m.label(z),
                    "Negative (< 0)": float(((p < 0) * w).sum()),
                    f"Surplus (≤ {SURPLUS:.0f} €/MWh)": float(((p <= SURPLUS) * w).sum()),
                    f"Low (< {LOW:.0f})": float(((p < LOW) * w).sum()),
                    f"High (> {HIGH:.0f})": float(((p > HIGH) * w).sum()),
                    "With market curtailment": float(((curt > 1.0) * w).sum()),
                    "Mean price": _wmean(p, w),
                })
        tbl = pd.DataFrame(rows).set_index("Configuration")
        # Chart: surplus hours per zone
        cats = [f"{r['Configuration'].split(' ')[0]} · {r['Zone'].split(' ')[0]}" for r in rows]
        colors = [SCENARIO_COLOR.get(next(k for k in self.M if SCENARIO_LABELS.get(k, k) == r["Configuration"]), "@muted")
                  for r in rows]
        f1 = self.fig("md-surplus", C.bars(cats, [
            {"name": "Surplus hours", "values": [r[f"Surplus (≤ {SURPLUS:.0f} €/MWh)"] for r in rows], "color": colors}],
            unit="hours per year", height=340, legend=False, digits=0))
        f2 = self.fig("md-curt-hours", C.bars(cats, [
            {"name": "Hours with market curtailment", "values": [r["With market curtailment"] for r in rows],
             "color": colors}], unit="hours per year", height=340, legend=False, digits=0))
        fmt = {c: (lambda v: H.fmt(v, 0)) for c in tbl.columns if c != "Mean price"}
        body = H.callout(
            "<strong>No negative prices in eTraGo.</strong> Every zone has 0 hours below 0 €/MWh: the market model "
            "has no negative bids (no market premium, must-run or subsidy effects), so the price floor is the "
            f"marginal cost of wind and solar (0.01–1.3 €/MWh). The IEE study models about 800 negative hours "
            f"per year. Here, <em>surplus hours</em> (price ≤ {SURPLUS:.0f} €/MWh, set by renewables) and hours "
            "with market curtailment are the equivalent indicators.", "warn") + H.grid(
            H.fig_block(f1, f"Surplus hours (price ≤ {SURPLUS:.0f} €/MWh)",
                        "Hours in which wind or solar set the zonal price."),
            H.fig_block(f2, "Hours with market curtailment in the zone",
                        "Curtailment chosen by the market (> 1 MW in the zone)."),
            H.table_block(tbl, "Hours per price band and zone", formats=fmt))
        self.add("hours", "Price levels and surplus hours",
                 "How often each zone sees very low, low and high prices.", body)

    def _zone_curt_ts(self, k, z):
        if not hasattr(self, "_curt_cache"):
            self._curt_cache = {}
        if k not in self._curt_cache:
            m = self.M[k]
            mk = m.mkt
            mg = mk.static("generators")
            sel = self.plants[k].index
            p = mk.series("generators", "p").reindex(columns=sel, fill_value=0)
            avail = mk.dense("generators", "p_max_pu", columns=sel).mul(mg.loc[sel, "p_nom"], axis=1)
            curt = (avail - p).clip(lower=0)
            zone = self._zone_of_plants(k)
            self._curt_cache[k] = curt.T.groupby(zone).sum().T
        df = self._curt_cache[k]
        return df[z] if z in df else pd.Series(0.0, index=self.M[k].prices.index)

    # ------------------------------------------------------------------
    def distribution(self):
        blocks = []
        edges = np.arange(0, 132, 2.0)
        centers = (edges[:-1] + edges[1:]) / 2
        for k, m in self.M.items():
            w = m.mkt.weights
            series = []
            for i, z in enumerate(m.de_zones):
                p = m.prices[z].clip(upper=edges[-1] - 0.01)
                h, _ = np.histogram(p.values, bins=edges, weights=w.values)
                mean = _wmean(m.prices[z], w)
                series.append({"name": f"{m.label(z).split(' ')[0]} (mean {mean:.1f})", "values": h,
                               "color": f"@s{i + 1}" if len(m.de_zones) > 1 else SCENARIO_COLOR[k]})
            spec = C.bars([f"{c:.0f}" for c in centers], series, unit="hours per year", height=300, digits=0)
            spec["layout"]["yaxis"].update({"type": "log", "dtick": 1})
            spec["layout"]["xaxis"] = {"title": {"text": "price [€/MWh], 2 €/MWh bins"}, "dtick": 10}
            spec["layout"]["bargap"] = 0.08
            spec["layout"]["bargroupgap"] = 0.0
            for tr in spec["data"]:
                tr["marker"]["line"] = {"width": 0}
            spec["layout"]["showlegend"] = True
            blocks.append(H.fig_block(self.fig(f"md-hist-{k}", spec), SCENARIO_LABELS.get(k, k)))
        self.add("distribution", "Price distribution",
                 "Hours per 2 €/MWh price band (logarithmic axis; IEE study slide 17). The IEE study shows the "
                 "north zone gaining low-price hours and losing high-price hours; here the German zones' "
                 "distributions lie almost on top of each other.", H.grid(*blocks))

    # ------------------------------------------------------------------
    def _week_hour(self, p, w):
        df = pd.DataFrame({"p": p.values, "w": w.values,
                           "d": p.index.dayofweek, "h": p.index.hour})
        g = df.groupby(["d", "h"]).apply(lambda x: _wmean(x.p, x.w)).unstack()
        return g.reindex(index=range(7), columns=range(24))

    def daily_pattern(self):
        m0 = self.M[self.sq]
        z0 = m0.de_zones[0]
        ref = self._week_hour(m0.prices[z0], m0.mkt.weights)
        vmin, vmax = float(np.nanmin(ref.values)), float(np.nanmax(ref.values))
        blocks = [H.fig_block(self.fig("md-wh-sq", C.heatmap(
            ref.values, [f"{h:02d}" for h in range(24)], WEEKDAYS, unit="€/MWh", height=300)),
            f"{SCENARIO_LABELS.get(self.sq)} – average price by weekday and hour")]
        self.figs["md-wh-sq"]["data"][0].update({"zmin": vmin, "zmax": vmax})
        for k in self.splits:
            m = self.M[k]
            z = m.focus_zone
            wh = self._week_hour(m.prices[z], m.mkt.weights)
            d = wh - ref
            vabs = max(0.5, float(np.nanmax(np.abs(d.values))))
            spec = C.heatmap(d.values, [f"{h:02d}" for h in range(24)], WEEKDAYS,
                             unit="Δ €/MWh vs single zone", scale="@divscale", zmid=0, height=300, digits=2)
            spec["data"][0].update({"zmin": -vabs, "zmax": vabs})
            blocks.append(H.fig_block(self.fig(f"md-wh-{k}", spec),
                                      f"{SCENARIO_LABELS.get(k, k)} – {m.label(z)} minus single zone"))
        self.add("daily", "Weekday × hour price profile",
                 "Average price per weekday and hour of day (IEE study, slide 18). The split configurations show "
                 "the difference of the zone containing Schleswig-Holstein to the single zone; blue = cheaper. "
                 "The 5-hour sampling cycles through all 24 hours, so every cell holds about ten snapshots.",
                 H.grid(*blocks))

    # ------------------------------------------------------------------
    def duration(self):
        series = []
        m0 = self.M[self.sq]
        n = len(m0.prices)
        idx = np.linspace(0, n - 1, min(n, 500)).astype(int)
        x = np.round(idx / (n - 1) * 8760).astype(int)
        series.append({"name": f"{SCENARIO_LABELS.get(self.sq)}", "values":
                       np.sort(m0.prices[m0.de_zones[0]].values)[::-1][idx], "color": "@ink", "width": 2.5})
        for k in self.splits:
            m = self.M[k]
            series.append({"name": f"{k}: {m.label(m.focus_zone)}",
                           "values": np.sort(m.prices[m.focus_zone].values)[::-1][idx],
                           "color": SCENARIO_COLOR.get(k)})
        spec = C.lines(x, series, unit="€/MWh", xtitle="hours of the year (sorted)", height=380)
        f1 = self.fig("md-pdc", spec)
        # zoom on the low-price tail
        spec2 = C.lines(x, series, unit="€/MWh", xtitle="hours of the year (sorted)", height=380)
        spec2["layout"]["xaxis"]["range"] = [4500, 8760]
        spec2["layout"]["yaxis"]["range"] = [0, 25]
        f2 = self.fig("md-pdc-zoom", spec2)
        self.add("duration", "Price duration curves of the SH zone",
                 "Sorted prices of the zone containing Schleswig-Holstein in each configuration against the single "
                 "zone (IEE study, slides 15–16).",
                 H.grid(H.fig_block(f1, "Full year"),
                        H.fig_block(f2, "Low-price part (zoom)",
                                    "Where a split shifts hours from the 5–20 €/MWh band to the renewable floor.")))

    # ------------------------------------------------------------------
    def zone_effects(self):
        """Market value of wind & PV, electrolyser utilisation and market
        curtailment per zone, change vs. the same plants in the single zone."""
        base = self.plants[self.sq]
        rows, maps = [], []
        e0 = self.M[self.sq]._ely_mkt
        e0 = e0[e0.zone.map(geo.is_german_zone).fillna(False).astype(bool)]
        ely_flh0 = e0.mwh.sum() / e0.p_nom.sum() if e0.p_nom.sum() else np.nan
        for k in self.splits:
            m = self.M[k]
            pl = self.plants[k]
            zone = self._zone_of_plants(k)
            labels = {}
            for z in m.de_zones:
                sel = zone.index[zone == z]
                r = {"Configuration": SCENARIO_LABELS.get(k, k), "Zone": m.label(z)}
                for name, car in (("Wind", WIND), ("PV", PV)):
                    a, b = pl.loc[sel], base.loc[sel]
                    a, b = a[a.carrier.isin(car)], b[b.carrier.isin(car)]
                    v = a.revenue.sum() / a.energy.sum() if a.energy.sum() else np.nan
                    v0 = b.revenue.sum() / b.energy.sum() if b.energy.sum() else np.nan
                    r[f"{name} market value [€/MWh]"] = v
                    r[f"{name} Δ vs single zone"] = v / v0 - 1 if v0 else np.nan
                a, b = pl.loc[sel], base.loc[sel]
                r["Market curtailment"] = a.curt.sum() / a.avail.sum() if a.avail.sum() else np.nan
                r["Curtailment single zone"] = b.curt.sum() / b.avail.sum() if b.avail.sum() else np.nan
                e = m._ely_mkt[m._ely_mkt.zone == z]
                flh = e.mwh.sum() / e.p_nom.sum() if e.p_nom.sum() else np.nan
                r["Electrolysis [GW]"] = e.p_nom.sum() / 1e3
                r["Electrolysis full-load h"] = flh
                r["Δ vs single-zone utilisation"] = flh / ely_flh0 - 1 if ely_flh0 else np.nan
                rows.append(r)
                labels[z] = r
            maps.append((k, labels))
        tbl = pd.DataFrame(rows).set_index("Configuration")
        blocks = []
        for metric, title, fmtf, key in [
            ("mv", "Market value wind / PV vs single zone", lambda r: f"{r['Wind Δ vs single zone'] * 100:+.0f} / {r['PV Δ vs single zone'] * 100:+.0f} %", "Wind Δ vs single zone"),
            ("ely", "Electrolyser utilisation vs single zone", lambda r: (f"{r['Δ vs single-zone utilisation'] * 100:+.0f} %" if np.isfinite(r['Δ vs single-zone utilisation']) else "–"), "Δ vs single-zone utilisation"),
            ("curt", "Market curtailment [% of potential]", lambda r: f"{r['Market curtailment'] * 100:.1f} % (SQ {r['Curtailment single zone'] * 100:.1f})", "Market curtailment"),
        ]:
            for k, labels in maps:
                m = self.M[k]
                vals = {z: r[key] for z, r in labels.items()}
                if metric == "curt":
                    fill = {z: C.seq(v, 0, 0.3) for z, v in vals.items()}
                else:
                    fill = {z: C.div(v, 0.6 if metric == "ely" else 0.15) for z, v in vals.items() if np.isfinite(v)}
                mp = base_map(m, geo.MAP_EXTENT["de"], zones_fill=fill, height=340)
                an = [zone_anchor(m, z) for z in labels]
                mp.labels([a[0] for a in an], [a[1] for a in an],
                          [f"<b>{m.label(z).split(' ')[0]}</b><br>{fmtf(r)}" for z, r in labels.items()], size=11)
                spec = mp.spec()
                spec["layout"]["showlegend"] = False
                blocks.append(H.fig_block(self.fig(f"md-{metric}-{k}", spec), f"{k}: {title}", table=False))
        pct = lambda v: H.pct(v, 1, signed=True)
        body = H.grid(*blocks, H.table_block(tbl, "Zone indicators vs single zone", formats={
            "Wind Δ vs single zone": pct, "PV Δ vs single zone": pct, "Δ vs single-zone utilisation": pct,
            "Market curtailment": lambda v: H.pct(v, 1), "Curtailment single zone": lambda v: H.pct(v, 1),
            "Electrolysis full-load h": lambda v: H.fmt(v, 0)}))
        self.add("zones", "Market values, electrolysis and curtailment per zone",
                 "IEE study slides 11–14: change of wind/PV market values (same plants, zonal vs single-zone "
                 "price), electrolyser utilisation and market curtailment per zone. Colour: red = higher, blue = "
                 "lower than in the single zone (saturates at ±15 % for market values, ±60 % for electrolysis).", body)

    # ------------------------------------------------------------------
    def explorer(self):
        blocks = []
        m0 = self.M[self.sq]
        p0 = m0.prices[m0.de_zones[0]]
        t0 = p0.index[0]
        init = [str(t0), str(t0 + pd.Timedelta(days=14))]
        for k in self.splits:
            m = self.M[k]
            x = [t.strftime("%Y-%m-%d %H:%M") for t in m.prices.index]
            data = [{"type": "scatter", "mode": "lines", "x": x, "y": C._r(p0.values, 2),
                     "name": "Single zone", "line": {"color": "@muted", "width": 1.5}, "yaxis": "y3",
                     "hovertemplate": "single zone: %{y:.2f} €/MWh<extra></extra>"}]
            for i, z in enumerate(m.de_zones):
                data.append({"type": "scatter", "mode": "lines", "x": x, "y": C._r(m.prices[z].values, 2),
                             "name": m.label(z), "line": {"color": f"@s{i + 1}", "width": 1.5}, "yaxis": "y3",
                             "hovertemplate": f"{m.label(z)}: %{{y:.2f}} €/MWh<extra></extra>"})
            fz = m.focus_zone
            others = [z for z in m.de_zones if z != fz]
            if others:
                spread = m.prices[fz] - m.prices[others].max(axis=1)
                data.append({"type": "scatter", "mode": "lines", "x": x, "y": C._r(spread.values, 2),
                             "name": "SH zone − most expensive DE zone", "fill": "tozeroy",
                             "line": {"color": "@div:0.14", "width": 1}, "fillcolor": "@fade:div:0.14", "yaxis": "y2",
                             "hovertemplate": "spread: %{y:.2f} €/MWh<extra></extra>"})
            net = pd.Series(0.0, index=m.prices.index)
            for (a, b), f in m.exchange_flows.items():
                if a == fz:
                    net = net + f
                elif b == fz:
                    net = net - f
            data.append({"type": "scatter", "mode": "lines", "x": x, "y": C._r(net.values / 1e3, 2),
                         "name": "SH zone net export", "line": {"color": "@s7", "width": 1.5}, "yaxis": "y",
                         "hovertemplate": "net export: %{y:.1f} GW<extra></extra>"})
            ely = m._ely_ts[fz] if fz in m._ely_ts else pd.Series(0.0, index=m.prices.index)
            data.append({"type": "scatter", "mode": "lines", "x": x, "y": C._r(ely.values / 1e3, 2),
                         "name": "SH zone electrolysis", "line": {"color": "@s3", "width": 1.5}, "yaxis": "y",
                         "hovertemplate": "electrolysis: %{y:.2f} GW<extra></extra>"})
            layout = {
                "hovermode": "x unified",
                "xaxis": {"type": "date", "range": init, "rangeslider": {"visible": True, "thickness": 0.06},
                          "rangeselector": {"buttons": [
                              {"count": 7, "label": "1 w", "step": "day", "stepmode": "backward"},
                              {"count": 1, "label": "1 m", "step": "month", "stepmode": "backward"},
                              {"count": 3, "label": "3 m", "step": "month", "stepmode": "backward"},
                              {"step": "all", "label": "year"}]}},
                "yaxis3": {"domain": [0.52, 1.0], "title": {"text": "zonal price [€/MWh]"}},
                "yaxis2": {"domain": [0.30, 0.48], "title": {"text": "spread [€/MWh]"}},
                "yaxis": {"domain": [0.0, 0.26], "title": {"text": "GW"}},
                "legend": {"orientation": "h", "y": 1.08},
            }
            blocks.append(H.fig_block(self.fig(f"md-ts-{k}", C.figure(data, layout, height=620)),
                                      f"{SCENARIO_LABELS.get(k, k)} – time-series explorer",
                                      "Top: zonal prices and the single-zone price. Middle: price of the SH zone minus "
                                      "the most expensive German zone (negative = SH cheaper). Bottom: net export of "
                                      "the SH zone and its electrolyser consumption. Use the buttons or the slider "
                                      "below to move through the year.", wide=True, table=False))
        self.add("explorer", "Time-series explorer",
                 "Full-year time series per configuration, starting with the first two weeks of January.",
                 H.grid(*blocks))
